type Props = SlotProps & { t: Translate }

async function copyText(text: string): Promise<boolean> {
  try {
    if (navigator.clipboard?.writeText !== undefined) {
      await navigator.clipboard.writeText(text)
      return true
    }
  } catch {
    /* fall through */
  }
  try {
    const area = document.createElement('textarea')
    area.value = text
    area.style.position = 'fixed'
    area.style.opacity = '0'
    document.body.appendChild(area)
    area.select()
    const ok = document.execCommand('copy')
    area.remove()
    return ok
  } catch {
    return false
  }
}

const ORDER: Record<ClaimStatus, number> = { none: 0, partial: 1, ok: 2 }

function ringColor(score: number | null): string {
  if (score === null) return 'var(--dsw-alias-state-idle-primary)'
  if (score >= 80) return 'var(--dsw-alias-state-success-primary)'
  if (score >= 50) return 'var(--dsw-alias-state-warn-primary)'
  return 'var(--dsw-alias-state-error-primary)'
}

function verdict(score: number | null): 'ok' | 'partial' | 'none' {
  if (score === null) return 'partial'
  if (score >= 80) return 'ok'
  if (score >= 50) return 'partial'
  return 'none'
}

function Ring(props: { score: number | null; label: string }): JSX.Element {
  const value = props.score ?? 0
  const color = ringColor(props.score)
  return (
    <div className="dea-ring">
      <svg viewBox="0 0 96 96" width={96} height={96} aria-hidden="true">
        <circle cx={48} cy={48} r={RING_R} fill="none" stroke="var(--dsw-alias-bg-layer-2)" strokeWidth={9} />
        <circle
          cx={48}
          cy={48}
          r={RING_R}
          fill="none"
          stroke={color}
          strokeWidth={9}
          strokeLinecap="round"
          strokeDasharray={`${(value / 100) * RING_C} ${RING_C}`}
          style={{ transition: 'stroke-dasharray .35s ease' }}
        />
      </svg>
      <div className="dea-ringV">
        <b style={{ color }}>{props.score === null ? '—' : `${props.score}%`}</b>
        <span>{props.label}</span>
      </div>
    </div>
  )
}

function ClaimCard(props: { claim: Claim; t: Translate }): JSX.Element {
  const { claim, t } = props
  const tag = claim.status === 'ok' ? t('tagOk') : claim.status === 'partial' ? t('tagPartial') : t('tagNone')
  return (
    <div className={`dea-card ${claim.status}`}>
      <div style={{ flex: 1, minWidth: 0 }}>
        <div className="dea-tag">{tag}</div>
        <p className="dea-cardT">{claim.text}</p>
        {claim.missing.length > 0 ? (
          <div className="dea-chips">
            {claim.missing.map((anchor, index) => (
              <span className="dea-chip" key={`${anchor}-${index}`} title={t('missing')}>
                {anchor}
              </span>
            ))}
          </div>
        ) : null}
      </div>
    </div>
  )
}

function EvidenceAudit(props: Props): JSX.Element {
  const { t } = props
  const nodes = props.useChat((snapshot) => snapshot.legacy?.nodes ?? [])
  const [open, setOpen] = useState(false)
  const [copied, setCopied] = useState(false)
  const closeRef = useRef<HTMLButtonElement | null>(null)

  const audit = useMemo(() => buildAudit(nodes as ChatNode[]), [nodes])
  const report = useMemo(() => buildReport(audit, t), [audit, t])
  const ordered = useMemo(() => [...audit.claims].sort((a, b) => ORDER[a.status] - ORDER[b.status]), [audit.claims])
  const total = audit.claims.length
  const tone = verdict(audit.score)

  useEffect(() => {
    if (!open) return undefined
    const onKey = (event: KeyboardEvent): void => {
      if (event.key === 'Escape') setOpen(false)
    }
    window.addEventListener('keydown', onKey)
    const timer = window.setTimeout(() => closeRef.current?.focus(), 30)
    return () => {
      window.removeEventListener('keydown', onKey)
      window.clearTimeout(timer)
    }
  }, [open])

  const onCopy = useCallback(() => {
    void copyText(report).then((ok) => {
      if (!ok) return
      setCopied(true)
      window.setTimeout(() => setCopied(false), 1600)
    })
  }, [report])

  const pill = (
    <button
      type="button"
      className="dea-pill"
      aria-haspopup="dialog"
      aria-expanded={open}
      title={t('title')}
      onClick={() => setOpen(true)}
    >
      {audit.score === null ? (
        <svg viewBox="0 0 16 16" width={13} height={13} aria-hidden="true">
          <circle cx={7} cy={7} r={4.4} fill="none" stroke="currentColor" strokeWidth={1.3} />
          <path d="M10.2 10.2L14 14" stroke="currentColor" strokeWidth={1.5} strokeLinecap="round" />
        </svg>
      ) : (
        <span className={`dea-pillDot ${tone}`} aria-hidden="true" />
      )}
      <span>{t('pill')}</span>
      {audit.score === null ? null : <span className="dea-pillScore">{audit.score}%</span>}
    </button>
  )

  if (!open) return pill

  const pct = (value: number): string => (total === 0 ? '0%' : `${(value / total) * 100}%`)

  const panel = (
    <div className="dea-modal" role="dialog" aria-modal="true" aria-label={t('title')} onClick={(event) => event.stopPropagation()}>
      <div className="dea-head">
        <div>
          <h2 className="dea-title">{t('title')}</h2>
          <p className="dea-sub">{t('sub')}</p>
        </div>
        <button type="button" className="dea-x" ref={closeRef} aria-label={t('close')} onClick={() => setOpen(false)}>
          ×
        </button>
      </div>

      {total === 0 ? (
        <div className="dea-empty">
          <b>{t('emptyTitle')}</b>
          {t('empty')}
        </div>
      ) : (
        <>
          <div className="dea-hero">
            <Ring score={audit.score} label={t('coverage')} />
            <div className="dea-stats">
              <div className="dea-stat">
                <i className="ok" />
                {t('ok')}
                <b>{audit.ok}</b>
                <span className="dea-bar" aria-hidden="true">
                  <span className="dea-seg-ok" style={{ width: pct(audit.ok), background: 'var(--dsw-alias-state-success-primary)' }} />
                </span>
              </div>
              <div className="dea-stat">
                <i className="partial" />
                {t('partial')}
                <b>{audit.partial}</b>
                <span className="dea-bar" aria-hidden="true">
                  <span style={{ width: pct(audit.partial), background: 'var(--dsw-alias-state-warn-primary)' }} />
                </span>
              </div>
              <div className="dea-stat">
                <i className="none" />
                {t('none')}
                <b>{audit.none}</b>
                <span className="dea-bar" aria-hidden="true">
                  <span style={{ width: pct(audit.none), background: 'var(--dsw-alias-state-error-primary)' }} />
                </span>
              </div>
            </div>
          </div>

          <div className="dea-body">
            {ordered.map((claim, index) => (
              <ClaimCard claim={claim} t={t} key={index} />
            ))}
          </div>
        </>
      )}

      <div className="dea-foot">
        <button type="button" className="dea-btn primary" onClick={onCopy} disabled={total === 0}>
          {copied ? t('copied') : t('copy')}
        </button>
        <span className="dea-note">{t('footnote')}</span>
      </div>
    </div>
  )

  return (
    <>
      {pill}
      {createPortal(
        <div className="dea-backdrop" onClick={() => setOpen(false)}>
          {panel}
        </div>,
        document.body,
      )}
    </>
  )
}

function makeT(ctx: ClientContext): Translate {
  let bound: Translate | null = null
  const locale = ctx.get('locale')
  if (locale !== undefined && typeof locale.register === 'function') {
    ctx.effect(() => {
      try {
        return locale.register(NS, DICT)
      } catch {
        return undefined
      }
    }, 'evidence-audit dictionaries')
    if (typeof locale.bind === 'function') bound = locale.bind(NS)
  }
  if (bound !== null) return bound

  const zh = typeof navigator !== 'undefined' && /^zh/i.test(navigator.language || '')
  const dictionary = zh ? DICT.zh : DICT.en
  return (key, params) => {
    let text = dictionary[key] ?? DICT.en[key] ?? key
    if (params !== undefined) {
      text = text.replace(/\{(\w+)\}/g, (match, name: string) => (name in params ? String(params[name]) : match))
    }
    return text
  }
}

export function apply(ctx: ClientContext): void {
  const t = makeT(ctx)
  const node = document.createElement('style')
  node.textContent = css
  document.head.appendChild(node)
  ctx.effect(() => () => node.remove(), 'evidence-audit styles')

  ctx.slots.inject(SLOT, () =>
    ctx.slots.register({ name: SLOT, id: ENTRY_ID, order: 4, label: () => t('pill') }, (props) => (
      <EvidenceAudit {...props} t={t} />
    )),
  )
}
